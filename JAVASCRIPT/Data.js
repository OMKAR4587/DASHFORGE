let selectedSector = null;

export function renderTreemap() {

    d3.select("#treemap").selectAll("*").remove();

    const container = document.getElementById("treemap");

    const width = container.clientWidth;
    const height = container.clientHeight;

    const svg = d3.select("#treemap")
        .append("svg")
        .attr("width", width)
        .attr("height", height);

    const currentData = selectedSector
        ? {
            name: selectedSector.data.name,
            children: selectedSector.data.children
        }
        : data;

    const root = d3.hierarchy(currentData)
        .sum(d => d.value || 0)
        .sort((a, b) => b.value - a.value);

    d3.treemap()
        .size([width, height])
        .paddingOuter(4)
        .paddingTop(32)
        .paddingInner(2)
        (root);

    if (selectedSector) {

        svg.append("text")
            .attr("x", 10)
            .attr("y", 15)
            .attr("class", "heapmap-market-button")
            .text(`MARKET / `)
            .attr("fill", "#ddd")
            .style("cursor", "pointer")
            .style("font-size", "18px")
            .style("text-decoration", "underline")
            .on("click", () => {

                selectedSector = null;

                renderTreemap();

            });

        svg.append("text")
            .attr("x", 100)
            .attr("y", 15)
            .text(selectedSector.data.name.toUpperCase())
            .attr("fill", "#ddd")
            .style("font-size", "16px");
    }

    if (!selectedSector) {

        const sectors = root.children || [];

        svg.selectAll(".sector-border")
            .data(sectors)
            .enter()
            .append("rect")
            .attr("class", "sector-border")
            .attr("x", d => d.x0)
            .attr("y", d => d.y0)
            .attr("width", d => d.x1 - d.x0)
            .attr("height", d => d.y1 - d.y0)
            .attr("fill", "none")
            .attr("stroke", "#444")
            .attr("stroke-width", 2);

        svg.selectAll(".sector-title")
            .data(sectors)
            .enter()
            .append("text")
            .attr("class", "sector-title")
            .attr("x", d => d.x0 + 8)
            .attr("y", d => d.y0 + 20)
            .text(d => d.data.name)
            .attr("fill", "white")
            .style("font-size", "16px")
            .style("font-weight", "bold")
            .style("cursor", "pointer")
            .on("click", (_, d) => {

                selectedSector = d;

                renderTreemap();

            });
    }

    const stocks = svg
        .selectAll(".stock-group")
        .data(root.leaves())
        .enter()
        .append("g")
        .attr("class", "stock-group");

    stocks.append("rect")
        .attr("x", d => d.x0)
        .attr("y", d => d.y0)
        .attr("width", d => d.x1 - d.x0)
        .attr("height", d => d.y1 - d.y0)

        .attr("fill", d => {

            return d.data.change >= 0
                ? "#2ca24f"
                : "#c0392b";

        })

        .attr("stroke", "#111")
        .attr("stroke-width", 2)

        .on("mouseenter", function () {

            d3.select(this)
                .attr("stroke", "#fff")
                .attr("stroke-width", 3);

        })

        .on("mouseleave", function () {

            d3.select(this)
                .attr("stroke", "#111")
                .attr("stroke-width", 2);

        });

    stocks.append("text")

        .filter(d => {

            return (
                (d.x1 - d.x0) > 70 &&
                (d.y1 - d.y0) > 40
            );

        })

        .attr("x", d => d.x0 + 8)
        .attr("y", d => d.y0 + 24)

        .text(d => d.data.name)

        .attr("fill", "white")

        .style("font-size", d => {

            const w = d.x1 - d.x0;

            return Math.max(
                10,
                Math.min(24, w / 8)
            ) + "px";

        })

        .style("font-weight", "bold")
        .style("pointer-events", "none");

    stocks.append("text")

        .filter(d => {

            return (
                (d.x1 - d.x0) > 90 &&
                (d.y1 - d.y0) > 70
            );

        })

        .attr("x", d => d.x0 + 8)
        .attr("y", d => d.y0 + 48)

        .text(d => `${d.data.change}%`)

        .attr("fill", "white")

        .style("font-size", d => {

            const w = d.x1 - d.x0;

            return Math.max(
                8,
                Math.min(18, w / 12)
            ) + "px";

        })

        .style("pointer-events", "none");
}